def build(name):
    clip = CLIPS[name]
    nodes = r6.build_rig()
    for joint, rows in clip["keys"].items():
        offset = (0, 0, 0) if joint == "Torso" else None
        r6.key(nodes, joint, 0, REST[joint], offset)
        for row in rows:
            r6.key(nodes, joint, row[0], row[1], row[2] if len(row) > 2 else None)
        r6.key(nodes, joint, clip["length"], REST[joint], offset)
    r6.fix_quaternion_flips(nodes)
    r6.smooth_location(nodes)
    return nodes, clip["length"]


def main():
    wanted = [a for a in sys.argv[1:] if not a.startswith("--")] or list(CLIPS)
    render = "--render" in sys.argv
    baked = {}
    for name in CLIPS:
        nodes, length = build(name)
        baked[name] = {"length": length, "data": r6.bake(nodes, length), "options": {"FadeIn": "0.03", "FadeOut": "0.12"}}
        if render and name in wanted:
            r6.setup_preview()
            bpy_scene = __import__("bpy").context.scene
            bpy_scene.render.resolution_x = 300
            bpy_scene.render.resolution_y = 300
            prefix = os.path.join(ROOT, "art", "preview", "frame_" + name.lower())
            times = [0.0, 0.07, 0.11, 0.135, 0.16, 0.22, 0.32, length - 0.06]
            paths = r6.render_frames(times, prefix)
            sheet = os.path.join(ROOT, "art", "preview", name.lower() + "_sheet.png")
            subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-pattern_type", "glob", "-i", prefix + "_*.png", "-filter_complex", "tile=8x1", sheet], check=True)
            for path in paths:
                os.remove(path)
    r6.write_luau(os.path.join(ROOT, "src", "shared", "Anim", "Baked.luau"), baked)
    print("baked", list(baked))


main()
